"""
Emit one instance as a runnable ``testcase()`` module and accumulate a
manifest.csv row (parameters <-> file) for later joining against model results.

The emitted file is ASCII-only and self-describing: it carries a _SPEC
provenance dict so any single file is traceable and regenerable.

Each task carries a 'theta' field — the paper's per-task ACET multiplier
(VII.A.2(f)).  Offline solvers ignore the extra key; the online simulator reads
it so that early-completion behaviour is reproducible DATA, not a config knob.
"""

import csv
import json
import os


_HEADER = [
    "file", "sweep", "set", "factor", "value",
    "n_prc", "n_tsk", "n_frq", "u_mand_factor", "u_opt_factor", "rho", "xi",
    "U_M", "U_O", "B", "H", "J",
    "e_mand_fmax", "e_full_fmax", "e_mand_min",
    "feasible", "donate_ok", "seed", "redraws",
]


def _fmt_tasks(tasks):
    out = []
    for t in tasks:
        eo = ", ".join(f"{e:.6f}" for e in t['e_o_k'])
        out.append(
            f"        {{'id': {t['id']}, 'e_m': {t['e_m']:.6f}, "
            f"'e_o_k': [{eo}], 'p_i': {int(t['p_i'])}, "
            f"'u_i': {t['u_i']:.4f}, 'theta': {t['theta']:.4f}}},"
        )
    return "\n".join(out)


def _fmt_procs(processors):
    out = []
    for p in processors:
        fr = ", ".join(str(f) for f in p['frequencies'])
        out.append(f"        {{'id': {p['id']}, 'frequencies': [{fr}]}},")
    return "\n".join(out)


def emit_testcase(path, ts, B, provenance):
    """Write a runnable testcase .py at `path`."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    spec_json = json.dumps(provenance, sort_keys=True)
    content = f'''"""Auto-generated USRT testcase -- DO NOT EDIT BY HAND.

Generated by usrt.gen following paper Section VII.A.
Each task carries 'theta': the per-task ACET multiplier (VII.A.2(f)); a segment
completes in theta * its worst-case execution time.

Provenance:
{spec_json}
"""

_SPEC = {spec_json!r}


def testcase():
    processors = [
{_fmt_procs(ts.processors)}
    ]
    tasks = [
{_fmt_tasks(ts.tasks)}
    ]
    B_BUDGET = {B:.6f}
    return processors, tasks, B_BUDGET
'''
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)


class ManifestWriter:
    """manifest.csv writer (one row per generated instance)."""

    def __init__(self, path):
        self.path = path
        os.makedirs(os.path.dirname(path), exist_ok=True)
        self._f = open(path, "w", newline="", encoding="utf-8")
        self._w = csv.DictWriter(self._f, fieldnames=_HEADER)
        self._w.writeheader()

    def row(self, **kw):
        self._w.writerow({k: kw.get(k, "") for k in _HEADER})

    def close(self):
        self._f.close()
