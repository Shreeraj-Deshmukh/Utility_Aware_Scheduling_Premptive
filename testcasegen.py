# --- This is the UUniFast algorithm you've used before ---
def uunifast(n, U_total):
    """
    Implements the UUniFast algorithm to generate 'n' task utilizations
    that sum exactly to 'U_total'.
    """
    s = [0.0] * (n + 1)
    s[n] = U_total
    
    for i in range(n, 1, -1):
        rand_num = random.random()
        s[i-1] = s[i] * (rand_num ** (1.0 / (i - 1)))
        
    utilizations = [s[i] - s[i-1] for i in range(1, n + 1)]
    return utilizations

def generate_testcase(task_count=10, total_utilization=1.0, energy_budget=8000, processor_count=2):
    """
    Generates a new, random testcase based on the given parameters.
    """
    
    # --- 1. Generate Processors ---
    # (Simple model, you can make this more complex)
    processors = []
    for i in range(processor_count):
        # Give each processor a few common frequencies
        processors.append({
            'id': i, 
            'frequencies': [0.6, 0.8, 1.0]
        })

    # --- 2. Generate Tasks ---
    utilizations = uunifast(task_count, total_utilization)
    tasks = []
    PERIOD_CHOICES = [20, 30, 40, 50, 60, 80, 100, 120, 200]

    for i in range(task_count):
        task_util = utilizations[i]
        p_i = random.choice(PERIOD_CHOICES)
        
        # We'll use the *total* utilization (mand + opt)
        # and assume 50% is mandatory
        total_e = task_util * p_i
        e_m = total_e * random.uniform(0.4, 0.6) # 40-60% is mandatory
        e_opt_total = total_e - e_m
        
        e_o_k = []
        num_optional_segments = random.randint(1, 4)
        
        if num_optional_segments > 0 and e_opt_total > 0:
            # Divide the optional time among the segments
            seg_times = [random.random() for _ in range(num_optional_segments)]
            total_rand = sum(seg_times)
            e_o_k = [(t / total_rand) * e_opt_total for t in seg_times]
        
        u_i = round(random.uniform(1.0, 3.5), 2)
        
        tasks.append({
            'id': i,
            'p_i': p_i,
            'e_m': e_m,
            'e_o_k': e_o_k,
            'u_i': u_i
        })
            
    return processors, tasks, energy_budget

